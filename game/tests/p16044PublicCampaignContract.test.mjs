import assert from 'node:assert/strict';
import fs from 'node:fs';
const moduleUrl = new URL('../src/utils/publicCampaign.mjs', import.meta.url);
assert(fs.existsSync(moduleUrl), 'P44 requires a real public campaign catalog');
const { PUBLIC_CHAPTERS, getPublicChapter, getNextPublicChapterId, getBattleChapter, resolveChapterPaintHit } = await import(moduleUrl);
assert.deepEqual(PUBLIC_CHAPTERS.map(c => c.id), ['opening', 'neon', 'encore', 'raincheck']);
assert.equal(getPublicChapter('bad').id, 'opening');
assert.equal(getNextPublicChapterId('opening'), 'neon');
assert.equal(getNextPublicChapterId('neon'), 'encore');
assert.equal(getNextPublicChapterId('encore'), 'raincheck');
assert.equal(getNextPublicChapterId('raincheck'), null);
assert.equal(getNextPublicChapterId('bad'), null);
assert.equal(getBattleChapter({stageId:1, campaignChapterId:'neon'}).id, 'neon');
assert.equal(getBattleChapter({stageId:1, practiceMode:true, campaignChapterId:'encore'}).id, 'opening');
for (const chapter of PUBLIC_CHAPTERS) {
  assert(Object.isFrozen(chapter));
  assert(Object.isFrozen(chapter.devices));
  assert.equal(chapter.devices.filter(d => d.required).length, 10);
  assert.equal(new Set(chapter.devices.map(d => d.id)).size, chapter.devices.length);
  assert.deepEqual([...new Set(chapter.devices.map(d => d.zone))].sort(), [0,1]);
  assert(chapter.devices.every(d => d.x > 40 && d.x < 960 && (d.zone === 0 ? d.y > 948 && d.y < 1750 : d.y < 900 && d.y > 100)));
  assert.equal(chapter.finalePatterns.length, 3);
}
assert.notDeepEqual(PUBLIC_CHAPTERS[0].devices.map(d => [d.x,d.y]), PUBLIC_CHAPTERS[1].devices.map(d => [d.x,d.y]));
assert.notDeepEqual(PUBLIC_CHAPTERS[1].devices.map(d => [d.x,d.y]), PUBLIC_CHAPTERS[2].devices.map(d => [d.x,d.y]));
assert.equal(resolveChapterPaintHit({paint:40,paintMax:52},14,'pink').complete,true);
const single = {paint:0,paintMax:52,colorSequence:['blue'],sequenceIndex:0};
assert.equal(resolveChapterPaintHit(single,99,'pink').accepted,false);
assert.equal(resolveChapterPaintHit(single,99).accepted,false);
assert.equal(resolveChapterPaintHit(single,52,'blue').complete,true);
const dual = {paint:0,paintMax:26,colorSequence:['blue','orange'],sequenceIndex:0};
const first = resolveChapterPaintHit(dual,999,'blue');
assert.deepEqual(first,{accepted:true,paint:0,sequenceIndex:1,complete:false});
const wrong = resolveChapterPaintHit({...dual,...first},999,'blue');
assert.equal(wrong.accepted,false);
assert.equal(wrong.paint,0);
const second = resolveChapterPaintHit({...dual,...first},26,'orange');
assert.equal(second.complete,true);
assert.equal(resolveChapterPaintHit({...dual,...second},10,'orange').accepted,false);
for(const bad of [0,-1,NaN,Infinity]) assert.equal(resolveChapterPaintHit(dual,bad,'blue').accepted,false);
assert.equal(PUBLIC_CHAPTERS[1].devices.filter(d=>d.required).every(d=>d.colorSequence.length===1),true);
assert.equal(PUBLIC_CHAPTERS[2].devices.filter(d=>d.required).every(d=>d.colorSequence.length===2 && d.colorSequence[0]!==d.colorSequence[1]),true);
console.log('p16044 campaign layouts, finite progression and real color phases: passed');
