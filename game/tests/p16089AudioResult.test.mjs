import assert from 'node:assert/strict';
import { createP17AudioController } from '../src/utils/p17AudioRuntime.mjs';
import { BATTLE_RESULT_TYPES } from '../src/utils/battleResult.mjs';
const played=[],ducks=[];
let available=true,success=true;
const scene={cache:{audio:{exists:()=>available}},sound:{play:(key)=>{played.push(key);return success;}},battleMusic:{duck:v=>ducks.push(v)}};
const audio=createP17AudioController(scene);
audio.playEncore({time:1000});
assert.equal(audio.playResult(BATTLE_RESULT_TYPES.VICTORY,{time:1100}).played,true,'victory must survive preceding Encore suppression');
assert.equal(audio.playResult(BATTLE_RESULT_TYPES.VICTORY,{time:1200}).played,false,'result stays one-shot');
assert.equal(ducks[0],0.9,'high priority SFX ducks the music');
success=false;
const failed=createP17AudioController(scene);
assert.equal(failed.playResult(BATTLE_RESULT_TYPES.VICTORY,{time:2000}).played,false);
success=true;
assert.equal(failed.playResult(BATTLE_RESULT_TYPES.VICTORY,{time:2010}).played,true,'unsuccessful audio call must not burn result slot');
delete scene.sound.play;
assert.equal(createP17AudioController(scene).playShotTick({time:3000}).played,false);
console.log('P16-089 result suppression, success accounting and music duck pass');
