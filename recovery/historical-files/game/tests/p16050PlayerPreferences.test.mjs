import assert from 'node:assert/strict';
import fs from 'node:fs';
const url=new URL('../src/utils/playerPreferences.mjs',import.meta.url);
assert.ok(fs.existsSync(url),'versioned player preferences are missing');
const {PlayerPreferences,PLAYER_PREFERENCES_KEY,applyPlayerAudioPreferences,getChapterBriefing}=await import(url);
const memory={raw:null,getItem(){return this.raw;},setItem(key,value){assert.equal(key,PLAYER_PREFERENCES_KEY);this.raw=value;}};
const prefs=new PlayerPreferences(()=>memory);
assert.deepEqual(prefs.read(),{version:1,muted:false,reducedEffects:false,volume:1,musicVolume:0.45,seenChapters:[],seenStoryIntros:[],storyProgress:[]});
assert.equal(prefs.update({volume:0.25,muted:true}).persisted,true);
assert.equal(new PlayerPreferences(()=>memory).read().volume,0.25);
assert.equal(prefs.update({volume:20}).value.volume,1);
assert.equal(prefs.update({volume:-1}).value.volume,0);
assert.equal(prefs.update({volume:NaN,muted:'false'}).value.muted,true);
prefs.update({volume:0.3,seenChapters:['opening','bad','opening']});
assert.deepEqual(prefs.read().seenChapters,['opening']);
memory.getItem=()=>{throw new Error('denied');};memory.setItem=()=>{throw new Error('denied');};
assert.equal(prefs.update({volume:0.6}).persisted,false);
assert.equal(prefs.read().volume,0.6);
const corrupt=new PlayerPreferences(()=>({getItem:()=>'{bad'}));
assert.equal(corrupt.read().volume,1);
let overwritten=false;
const future=new PlayerPreferences(()=>({getItem:()=>'{"version":99}',setItem:()=>overwritten=true}));
assert.equal(future.update({muted:true}).persisted,false);assert.equal(overwritten,false);
const calls=[];applyPlayerAudioPreferences({setVolume:v=>calls.push(['volume',v]),setMute:v=>calls.push(['mute',v])},prefs.read());
assert.deepEqual(calls,[['volume',0.6],['mute',true]]);
assert.match(getChapterBriefing('opening').rule,/攻击会给经过的街面铺上颜色/);
assert.match(getChapterBriefing('neon').rule,/无需逐台配色/);
assert.match(getChapterBriefing('encore').rule,/两段/);
console.log('P16-050 preferences, persistence, audio gain and three rule contracts pass');
